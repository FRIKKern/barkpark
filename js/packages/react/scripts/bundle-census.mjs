#!/usr/bin/env node
// Sourcemap-free, esbuild-metafile-backed PER-SOURCE-FILE BYTE CENSUS of the
// bundles `.size-limit.json` measures.
//
// WHY THIS AND NOT `dist/*.mjs.map`
// --------------------------------
// The size budgets do NOT measure `dist/*.mjs`. Those entries are thin
// re-export shims (`dist/portable-doc.mjs` is 159 B on disk) pointing at a
// shared 110 KB `chunk-*.mjs`. size-limit re-bundles each entry from scratch
// with esbuild (bundle + minify + treeShaking) and gzips THAT. So attributing
// the on-disk chunk's sourcemap would census a payload nobody's budget reads,
// and it could not reconcile against the reported number.
//
// This tool instead replicates size-limit's own esbuild invocation verbatim —
// see `@size-limit/esbuild/get-config.js`, mirrored in `sizeLimitEsbuildConfig`
// below — with `metafile: true`. esbuild's metafile reports, per OUTPUT file,
// `inputs[<source>].bytesInOutput`: the exact number of post-minify,
// post-treeshake bytes each original module contributed. That is the census.
//
// It builds no package: it consumes the `dist/*.mjs` that `pnpm run build`
// already produced. Run `pnpm run build` first (build `js/packages/core`
// BEFORE `js/packages/react`, or the dts step fails).
//
// RECONCILIATION
// --------------
// Every table prints `attributed + unattributed = output size`. `unattributed`
// is esbuild's own bundle scaffolding (module wrappers, re-export plumbing,
// the `__export`/`__toESM` helpers) that belongs to no input file. An
// attribution that does not reconcile is a guess wearing a table's clothes, so
// the check is printed, not assumed.
//
// UNITS — READ THIS BEFORE QUOTING A NUMBER
// -----------------------------------------
// Per-file bytes are RAW MINIFIED bytes. The BUDGET is GZIPPED. gzip is not
// additive over a partition of its input, so there is no honest per-file
// gzipped number to print and this tool does not invent one. Each entry's
// header prints raw total, gzipped total, and the ratio between them, so a
// reader can scale a raw saving into an approximate gzipped one — and knows
// they are doing so.
//
// CONTROL
// -------
// `measured gzipped` here must equal what `pnpm run size` prints for the same
// entry, to the byte. It is not a restatement of size-limit's number — it is
// computed independently from this tool's own bundle — so a drift between this
// config and `@size-limit/esbuild` shows up as a mismatch instead of hiding.
// Cross-check the two outputs before trusting a row.
//
// TWO TABLES, TWO QUESTIONS
// -------------------------
// `--chunks` answers "which dist artifact", straight off the metafile. Its rows
// bottom out at `dist/chunk-*.mjs` — 85-99.6% of the payload in one opaque
// line, which is not an answer.
//
// The DEFAULT table descends through those chunks' own sourcemaps to the
// ORIGINAL `src/*.ts(x)` files. esbuild consumes the `//# sourceMappingURL` on
// each `dist/*.mjs` input, so a second pass with `sourcemap: 'external'` emits
// a map from the FINAL MINIFIED bundle straight back to the TypeScript. Bytes
// are then assigned by walking that map's segments in generated order: a
// segment owns the generated bytes from its column to the next segment's.
// `'external'` puts the map in its own file and adds no `sourceMappingURL`
// comment, so the measured `.js` is byte-identical to the no-sourcemap build —
// asserted at runtime, not assumed (`sourcemapPassChangedBytes`).
//
// Usage:
//   node scripts/bundle-census.mjs                 # every .size-limit.json entry
//   node scripts/bundle-census.mjs --over          # only entries over their limit
//   node scripts/bundle-census.mjs --json          # machine-readable
//   node scripts/bundle-census.mjs --top 25        # rows per entry (default 30)
//   node scripts/bundle-census.mjs --chunks        # dist-artifact table instead
//   node scripts/bundle-census.mjs --gz            # add the MEASURED gzipped column
//
// `--gz` — THE COLUMN THE BUDGET ACTUALLY SPEAKS IN
// ------------------------------------------------
// The raw column above is an ESTIMATE of budget cost: the budget is gzipped and
// gzip is not additive, so scaling a raw saving by the header's ratio is a
// guess. `--gz` stops guessing. For each source file it EXCISES exactly the
// generated byte ranges the sourcemap attributes to that file, re-gzips the
// remaining stream, and prints `gzip(full) - gzip(excised)`. That is a
// measurement of this bundle's own gzip, not a ratio applied to a raw number.
//
// WHAT IT IS AND IS NOT, said plainly so no reader over-claims a row:
//   IS  — the gzipped bytes this file's minified output costs IN THIS STREAM.
//         Deleting exactly these bytes and no others frees exactly this many.
//   NOT — a prediction of what deleting the SOURCE would save. A real deletion
//         also drops the imports, helpers and dispatch entries that only it
//         used, and changes what the remaining bytes can back-reference. The
//         only way to get that number is to delete the code and rebuild.
// Rows are therefore a LOWER-ish BOUND ON THE FLOOR of a candidate, ranked
// honestly. A candidate worth pursuing is confirmed by a real rebuild and
// `pnpm run size`, never by this column alone.

import { gzipSync } from 'node:zlib'
import { mkdtempSync, readFileSync, rmSync, statSync } from 'node:fs'
import { createRequire } from 'node:module'
import { tmpdir } from 'node:os'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

// Borrow the EXACT esbuild instance `@size-limit/esbuild` will run, by
// resolving through the already-present `@size-limit/preset-small-lib` devDep
// rather than declaring an `esbuild` dependency of our own.
//
// Two reasons, and the second is the load-bearing one:
//   1. A declared `esbuild` here is a version PIN that can silently drift from
//      whatever size-limit resolves, and the day it drifts this tool starts
//      reporting a bundle nobody measures — quietly, because the numbers still
//      look plausible. Resolving through size-limit cannot drift: it is the
//      same file on disk.
//   2. The repo-root pnpm workspace (`pnpm-workspace.yaml`: web, js/packages/*,
//      apps/mobile) hoists a single esbuild, and `vite@8` there wants
//      `^0.27 || ^0.28`. Adding `esbuild@0.25.12` to satisfy size-limit put an
//      unmet peer on vite across the whole root workspace — a dev-only census
//      tool has no business moving web/'s build toolchain.
const req = createRequire(import.meta.url)
const esbuild = await import(
  pathToFileURL(
    req.resolve('esbuild', {
      paths: [
        req.resolve('@size-limit/esbuild', {
          paths: [req.resolve('@size-limit/preset-small-lib')],
        }),
      ],
    }),
  )
).then(m => m.default ?? m)

const PKG = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const argv = process.argv.slice(2)
const onlyOver = argv.includes('--over')
const asJson = argv.includes('--json')
const byChunk = argv.includes('--chunks')
const withGzip = argv.includes('--gz')
const topN = (() => {
  const i = argv.indexOf('--top')
  return i === -1 ? 30 : Number(argv[i + 1]) || 30
})()

const B64 = new Map(
  [...'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'].map(
    (c, i) => [c, i],
  ),
)

// Standard base64-VLQ segment decoder. Returns one array of segments per
// generated line; each segment is [generatedColumn, sourceIndex] and segments
// with no source field (1-length) become [generatedColumn, null] — a real
// boundary that ends the previous source's run without starting a new one.
function decodeMappings(mappings) {
  const lines = []
  let sourceIdx = 0
  for (const lineStr of mappings.split(';')) {
    const segs = []
    let genCol = 0
    if (lineStr) {
      for (const segStr of lineStr.split(',')) {
        if (!segStr) continue
        const fields = []
        let value = 0
        let shift = 0
        for (const ch of segStr) {
          const digit = B64.get(ch)
          if (digit === undefined) break
          value += (digit & 31) << shift
          if (digit & 32) {
            shift += 5
          } else {
            const neg = value & 1
            value >>= 1
            fields.push(neg ? -value : value)
            value = 0
            shift = 0
          }
        }
        genCol += fields[0] ?? 0
        if (fields.length === 1) {
          segs.push([genCol, null])
        } else {
          sourceIdx += fields[1]
          segs.push([genCol, sourceIdx])
        }
      }
    }
    lines.push(segs)
  }
  return lines
}

// Assign every byte of `code` to the original source that the map says produced
// it. A segment owns [its generated column, the next segment's column); bytes
// before the first segment on a line, bytes on segment-less lines, and the
// newlines themselves belong to no source and land in `unattributed`.
// Columns are UTF-16 code units (per the source-map spec), so spans are sliced
// as UTF-16 and only then measured in bytes — the two differ wherever a string
// literal is non-ASCII.
function attributeViaSourcemap(code, map) {
  const perSource = new Map()
  // Same partition as `perSource`, kept as [start, end) UTF-16 offsets into
  // `code` so `--gz` can excise exactly these bytes and re-gzip. Built here, not
  // re-derived later, so the gzipped column and the raw column can never
  // describe two different partitions of the stream.
  const spans = new Map()
  let unattributed = 0
  let base = 0
  const add = (idx, bytes, from, to) => {
    if (bytes <= 0) return
    if (idx == null) unattributed += bytes
    else {
      perSource.set(idx, (perSource.get(idx) || 0) + bytes)
      const list = spans.get(idx)
      if (list) list.push([from, to])
      else spans.set(idx, [[from, to]])
    }
  }

  const lines = code.split('\n')
  const decoded = decodeMappings(map.mappings)
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]
    if (i > 0) {
      unattributed += 1 // the '\n' that joined this line to the last
      base += 1
    }
    const segs = decoded[i] || []
    if (segs.length === 0) {
      unattributed += Buffer.byteLength(line)
      base += line.length
      continue
    }
    add(null, Buffer.byteLength(line.slice(0, segs[0][0])))
    for (let j = 0; j < segs.length; j++) {
      const end = j + 1 < segs.length ? segs[j + 1][0] : line.length
      add(
        segs[j][1],
        Buffer.byteLength(line.slice(segs[j][0], end)),
        base + segs[j][0],
        base + end,
      )
    }
    base += line.length
  }

  return { perSource, spans, unattributed }
}

// size-limit prepends the package's peerDependencies to every check's `ignore`
// (`size-limit/get-config.js`, `check.ignore = peer.concat(check.ignore || [])`),
// so react/react-dom are external in the measured bundle even though no entry
// lists them. Miss this and every census over-counts by ~7.5 KB of
// react.production.js that the budget never saw.
const PEER = Object.keys(
  JSON.parse(readFileSync(join(PKG, 'package.json'), 'utf8')).peerDependencies ||
    {},
)

// @size-limit/esbuild subtracts the size of an empty esbuild project from every
// measurement (`ESBUILD_EMPTY_PROJECT_GZIP`, index.js step61). Reproduced so the
// census's gzipped total equals the number `pnpm run size` prints, to the byte.
const ESBUILD_EMPTY_PROJECT_GZIP = 32

// Mirrors @size-limit/esbuild/get-config.js exactly, plus `metafile` (already
// true there) and `write: false` so nothing lands on disk. Drift here silently
// turns the census into fiction, so the reconciliation + gzip cross-check
// against the entry's `limit` is the guard: if this config stops matching what
// size-limit runs, the gzipped total stops matching what size-limit reports.
function sizeLimitEsbuildConfig(entryPoints, external, outdir) {
  return {
    bundle: true,
    entryPoints,
    external,
    metafile: true,
    minifyIdentifiers: true,
    minifySyntax: true,
    minifyWhitespace: true,
    outdir,
    treeShaking: true,
    write: false,
  }
}

function parseLimit(limit) {
  if (typeof limit !== 'string') return null
  const m = limit.trim().match(/^([\d.]+)\s*(B|KB|kB|MB)?$/)
  if (!m) return null
  const n = Number(m[1])
  const unit = (m[2] || 'B').toLowerCase()
  return unit === 'kb' ? n * 1000 : unit === 'mb' ? n * 1000 * 1000 : n
}

function fmt(n) {
  return n.toLocaleString('en-US')
}

// MEASURED gzipped cost of one source file's contribution: excise exactly the
// generated spans attributed to it, gzip what is left, and subtract. Spans are
// removed back-to-front so earlier offsets stay valid. This is a measurement of
// the real stream, never a ratio applied to a raw number — see the `--gz` note
// at the top for what the resulting number does and does not license.
function gzipCostOfSpans(code, spanList, baseline) {
  if (!spanList || spanList.length === 0) return 0
  const sorted = [...spanList].sort((a, b) => a[0] - b[0])
  let out = ''
  let cursor = 0
  for (const [from, to] of sorted) {
    if (from > cursor) out += code.slice(cursor, from)
    if (to > cursor) cursor = to
  }
  out += code.slice(cursor)
  return baseline - gzipSync(Buffer.from(out, 'utf8'), { level: 9 }).byteLength
}

async function censusEntry(check) {
  const entryPath = Array.isArray(check.path) ? check.path : [check.path]
  const abs = entryPath.map(p => resolve(PKG, p))
  for (const f of abs) statSync(f) // loud failure if dist is missing

  const external = PEER.concat(check.ignore || [])
  const outdir = mkdtempSync(join(tmpdir(), 'bundle-census-'))
  let result
  let mapped
  try {
    result = await esbuild.build(sizeLimitEsbuildConfig(abs, external, outdir))
    mapped = await esbuild.build({
      ...sizeLimitEsbuildConfig(abs, external, outdir),
      sourcemap: 'external',
    })
  } finally {
    rmSync(outdir, { force: true, recursive: true })
  }

  const out = result.outputFiles.find(f => f.path.endsWith('.js'))
  const meta = Object.entries(result.metafile.outputs).find(([k]) =>
    k.endsWith('.js'),
  )[1]

  const mappedJs = mapped.outputFiles.find(f => f.path.endsWith('.js'))
  const mappedMap = JSON.parse(
    Buffer.from(
      mapped.outputFiles.find(f => f.path.endsWith('.js.map')).contents,
    ).toString('utf8'),
  )
  // CONTROL: the sourcemap pass must not move a single byte of the thing being
  // measured, or the source-level table describes a different bundle than the
  // budget does.
  const sourcemapPassChangedBytes =
    mappedJs.contents.byteLength !== out.contents.byteLength

  const rawTotal = out.contents.byteLength
  const gzipTotal =
    gzipSync(Buffer.from(out.contents), { level: 9 }).byteLength -
    ESBUILD_EMPTY_PROJECT_GZIP

  const rows = Object.entries(meta.inputs)
    .map(([source, v]) => ({
      source: source.startsWith('..') ? source : relative(PKG, resolve(source)),
      bytes: v.bytesInOutput,
    }))
    .filter(r => r.bytes > 0)
    .sort((a, b) => b.bytes - a.bytes)

  const attributed = rows.reduce((s, r) => s + r.bytes, 0)

  // Map `sources` are relative to the (now-deleted) tmp outdir; re-anchor them
  // on the repo root so a row reads `js/packages/react/src/blocks/core.ts`.
  const REPO = resolve(PKG, '..', '..', '..')
  const mappedText = Buffer.from(mappedJs.contents).toString('utf8')
  const {
    perSource,
    spans,
    unattributed: srcUnattributed,
  } = attributeViaSourcemap(mappedText, mappedMap)
  // The `--gz` baseline is the SOURCEMAP-PASS stream, not `out`, because the
  // spans index into that stream. `sourcemapPassChangedBytes` already asserts
  // the two are byte-identical, so the baseline is the measured bundle.
  const gzipBaseline = withGzip
    ? gzipSync(Buffer.from(mappedText, 'utf8'), { level: 9 }).byteLength
    : null
  const srcRows = [...perSource.entries()]
    .map(([idx, bytes]) => ({
      bytes,
      gzipBytes: withGzip ? gzipCostOfSpans(mappedText, spans.get(idx), gzipBaseline) : null,
      source: relative(REPO, resolve(outdir, mappedMap.sources[idx])),
    }))
    .sort((a, b) => b.bytes - a.bytes)
  const srcAttributed = srcRows.reduce((s, r) => s + r.bytes, 0)

  return {
    attributed,
    sourcemapPassChangedBytes,
    srcAttributed,
    srcRows,
    srcUnattributed,
    gzipTotal,
    limit: parseLimit(check.limit),
    limitText: check.limit,
    name: check.name,
    path: check.path,
    rawTotal,
    rows,
    unattributed: rawTotal - attributed,
  }
}

function printEntry(e) {
  const over = e.limit != null ? e.gzipTotal - e.limit : null
  const ratio = (e.rawTotal / e.gzipTotal).toFixed(2)

  console.log('='.repeat(78))
  console.log(e.path)
  console.log(e.name)
  console.log('-'.repeat(78))
  console.log(
    `  measured gzipped : ${fmt(e.gzipTotal)} B   limit ${e.limitText} (${fmt(e.limit)} B)   ` +
      (over == null ? '' : over > 0 ? `OVER by ${fmt(over)} B` : `under by ${fmt(-over)} B`),
  )
  console.log(`  raw minified     : ${fmt(e.rawTotal)} B   (gzip ratio ${ratio}:1)`)
  console.log(
    `  RECONCILES       : ${fmt(e.attributed)} attributed + ${fmt(e.unattributed)} unattributed = ${fmt(e.attributed + e.unattributed)} = ${fmt(e.rawTotal)} raw  ` +
      (e.attributed + e.unattributed === e.rawTotal ? 'OK' : 'MISMATCH') +
      '  [dist artifacts, via metafile]',
  )
  console.log(
    `  RECONCILES       : ${fmt(e.srcAttributed)} attributed + ${fmt(e.srcUnattributed)} unattributed = ${fmt(e.srcAttributed + e.srcUnattributed)} = ${fmt(e.rawTotal)} raw  ` +
      (e.srcAttributed + e.srcUnattributed === e.rawTotal ? 'OK' : 'MISMATCH') +
      '  [original sources, via sourcemap]',
  )
  if (e.sourcemapPassChangedBytes) {
    console.log(
      '  !! sourcemap pass changed the bundle bytes — source table is NOT the measured bundle',
    )
  }
  console.log('-'.repeat(78))

  const rows = byChunk ? e.rows : e.srcRows
  const attributed = byChunk ? e.attributed : e.srcAttributed
  const unattributed = byChunk ? e.unattributed : e.srcUnattributed
  const gzCol = withGzip && !byChunk
  if (gzCol) {
    console.log(
      '   raw B    %tot    gz B*   original source   (* MEASURED: gzip(full) - gzip(this file excised).',
    )
    console.log(
      '                                              Not what deleting the source would save — see --gz note.)',
    )
  } else {
    console.log(
      byChunk
        ? '   raw B    %tot   dist artifact (raw minified bytes; budget is GZIPPED)'
        : '   raw B    %tot   original source (raw minified bytes; budget is GZIPPED)',
    )
  }

  // CONTROL, printed not assumed: a gzipped column derived by scaling raw bytes
  // through the header ratio would sum to the gzipped total. A MEASURED one
  // cannot — every file's excision leaves the others able to back-reference the
  // shared literals it used to supply, so the parts always sum to LESS than the
  // whole. A sum at or above the total means this column stopped being a
  // measurement. The shortfall is the payload's shared-substring overlap.
  if (gzCol) {
    const gzSum = e.srcRows.reduce((s2, r) => s2 + r.gzipBytes, 0)
    console.log(
      `  SUB-ADDITIVE     : gz column sums to ${fmt(gzSum)} B vs ${fmt(e.gzipTotal)} B measured total ` +
        `(${gzSum < e.gzipTotal ? 'OK' : 'BROKEN — this is a ratio, not a measurement'}; ` +
        `${fmt(e.gzipTotal - gzSum)} B is cross-file gzip overlap)`,
    )
    console.log('-'.repeat(78))
  }

  let shown = 0
  for (const r of rows.slice(0, topN)) {
    shown += r.bytes
    const head = `  ${String(fmt(r.bytes)).padStart(8)}  ${((r.bytes / e.rawTotal) * 100).toFixed(1).padStart(5)}%`
    console.log(
      gzCol
        ? `${head}  ${String(fmt(r.gzipBytes)).padStart(7)}   ${r.source}`
        : `${head}   ${r.source}`,
    )
  }
  const rest = rows.length - topN
  if (rest > 0) {
    console.log(
      `  ${String(fmt(attributed - shown)).padStart(8)}  ${(((attributed - shown) / e.rawTotal) * 100).toFixed(1).padStart(5)}%   (+${rest} more)`,
    )
  }
  console.log(
    `  ${String(fmt(unattributed)).padStart(8)}  ${((unattributed / e.rawTotal) * 100).toFixed(1).padStart(5)}%   <bundle scaffolding / unmapped — no source file>`,
  )
  console.log()
}

const config = JSON.parse(readFileSync(join(PKG, '.size-limit.json'), 'utf8'))
const results = []
for (const check of config) {
  if (check.import) continue // synthetic named-import entry, not a dist file
  const e = await censusEntry(check)
  if (onlyOver && !(e.limit != null && e.gzipTotal > e.limit)) continue
  results.push(e)
}

if (asJson) {
  console.log(JSON.stringify(results, null, 2))
} else {
  for (const e of results) printEntry(e)
}
