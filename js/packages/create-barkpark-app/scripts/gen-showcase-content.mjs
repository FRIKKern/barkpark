#!/usr/bin/env node
// gen-showcase-content.mjs — regenerate the blog-starter's kitchen-sink seed.
//
// The flagship demo post's body is the FULL 42-type PortableDocument grammar.
// Rather than hand-author 42 blocks (which drifts from the canonical renderer's
// parity fixtures), we CONCATENATE the `.input` object of every pd-golden
// fixture that already proves `@barkpark/react`'s PortableDoc renders shape-equal
// to the Phoenix `:article` golden. One source of truth: the parity fixtures.
//
//   node scripts/gen-showcase-content.mjs      # rewrite seeds/showcase-content.ts
//
// Deterministic (fixtures sorted by filename) + idempotent. Re-run whenever the
// pd-golden set changes; the showcase test fails if this file drifts from it.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
// create-barkpark-app/scripts → js/packages/react/tests/fixtures/pd-golden
const GOLDEN_DIR = join(here, '..', '..', 'react', 'tests', 'fixtures', 'pd-golden')
const OUT = join(here, '..', 'templates', 'blog-starter', 'seeds', 'showcase-content.ts')

const files = readdirSync(GOLDEN_DIR)
  .filter((f) => f.endsWith('.golden.json'))
  .sort()

const blocks = files.map((f) => {
  const g = JSON.parse(readFileSync(join(GOLDEN_DIR, f), 'utf8'))
  if (!g.input || typeof g.input.type !== 'string') {
    throw new Error(`pd-golden ${f} has no type-keyed .input block`)
  }
  return g.input
})

const types = blocks.map((b) => b.type)
if (new Set(types).size !== types.length) {
  throw new Error('duplicate block type across pd-golden fixtures')
}

const header = `// AUTO-GENERATED by scripts/gen-showcase-content.mjs — DO NOT hand-edit.
//
// The full ${blocks.length}-type PortableDocument grammar, one block per registered
// non-plugin type, lifted verbatim from @barkpark/react's pd-golden parity
// fixtures. This is the flagship demo post's body: it renders through the
// canonical PortableDoc renderer (index + post pages) and hydrates its media
// mount points (mermaid diagram + asciicast) via @barkpark/react/client.
//
// Regenerate with: node scripts/gen-showcase-content.mjs

import type { Block } from '@barkpark/react'

/** The ${blocks.length} canonical block types, concatenated from the parity goldens. */
export const showcaseContent: Block[] = ${JSON.stringify(blocks, null, 2)}

export default showcaseContent
`

writeFileSync(OUT, header)
console.log(`wrote ${OUT} — ${blocks.length} blocks: ${types.join(', ')}`)
