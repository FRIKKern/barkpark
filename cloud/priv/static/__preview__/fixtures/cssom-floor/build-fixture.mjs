// build-fixture.mjs — regenerates the cssom-floor ratchet proof fixtures.
//
// WHY THESE FIXTURES EXIST. cssom-parity.mjs's D20 predecessor proved its count
// check could fail exactly ONCE — a stray `/*` inserted into app.css, run, reverted.
// That is a one-time, ephemeral proof. D65's exact-match sidecar ratchet needs a
// PERMANENT one: a committed stylesheet whose head count sits ABOVE app.css's live
// baseline, so a swallow ABOVE that baseline can be shown to red — the exact decay
// case a STATIC floor of 1201/1203 would sail straight over. These fixtures are that
// proof, committed and re-runnable by anyone via proof.sh; nothing is reverted.
//
// TOTAL heads = 1300 (> app.css's live 1203, and far above the retired 1201 floor).
// The swallowed variant comments out a contiguous 60-rule run with a stray `/*`
// opener that pairs with a `*/` closer 60 rules later — a SYMMETRIC loss: the
// brace-tracking parser and Chrome both drop those 60, so MISSES stays 0 and the
// ONLY signal is the count. 1300 → 1240, still 37 above app.css's baseline, so this
// is unambiguously a swallow the static floor could never have caught.
//
// Deterministic: same bytes every run. Regenerate with `node build-fixture.mjs`.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const TOTAL = 1300;
const SWALLOW_START = 500; // 0-based index of the first rule to comment out
const SWALLOW_COUNT = 60;

// Distinct selector + distinct declaration per rule so authored heads == CSSOM
// rules exactly, with nothing Chrome would dedupe or fold.
const rule = (i) => `.cssom-floor-fixture-${String(i).padStart(4, "0")} { color: #${String(i).padStart(6, "0")} }`;

const rules = Array.from({ length: TOTAL }, (_, i) => rule(i));

const header =
  "/* GENERATED by build-fixture.mjs — do not hand-edit. See its header for why. */\n";

// Clean: all TOTAL rules reach the CSSOM.
fs.writeFileSync(path.join(HERE, "heads.css"), header + rules.join("\n") + "\n");

// Swallowed: a stray `/*` before rule SWALLOW_START and a `*/` after the last
// swallowed rule turn SWALLOW_COUNT live rules into comment text — a symmetric loss.
const swallowed = rules.slice();
swallowed[SWALLOW_START] = "/*\n" + swallowed[SWALLOW_START];
swallowed[SWALLOW_START + SWALLOW_COUNT - 1] = swallowed[SWALLOW_START + SWALLOW_COUNT - 1] + "\n*/";
fs.writeFileSync(path.join(HERE, "heads.swallowed.css"), header + swallowed.join("\n") + "\n");

// The committed baseline for the CLEAN fixture. The swallowed run is checked
// against THIS same baseline (proof.sh), which is the whole point: an exact-match
// ratchet reds the moment the count leaves it.
const baseline =
  "# Baseline for heads.css (the cssom-floor ratchet proof fixture).\n" +
  `# ${TOTAL} authored heads — deliberately ABOVE app.css's live count so proof.sh can\n` +
  "# show a swallow ABOVE the app.css baseline still reds. Regenerate via build-fixture.mjs.\n" +
  `${TOTAL}\n`;
fs.writeFileSync(path.join(HERE, "heads.baseline"), baseline);

process.stdout.write(
  `wrote heads.css (${TOTAL} rules), heads.swallowed.css (${TOTAL - SWALLOW_COUNT} live rules), heads.baseline (${TOTAL})\n`,
);
