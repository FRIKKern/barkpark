defmodule Barkpark.PortableDoc.Spec do
  @moduledoc """
  The PortableDoc block spec as a JSON Schema (draft-07): every block type the
  reader renders, its fields (`Spec.Fields`), its composition tier
  (`Barkpark.PortableDoc.Tiers`, as `x-tier`) and the structure constraint
  vocabulary (`Barkpark.PortableDoc.Constraints`, read off its typespecs).

  `mix barkpark.portable_doc.gen_spec` writes `json/0` to `path/0`. The file is
  public: it syncs to the portable-doc repo as `spec/blocks.schema.json`.
  """

  alias Barkpark.PortableDoc.{Constraints, Tiers}
  alias Barkpark.PortableDoc.Spec.Fields

  @path Path.expand("../../../priv/portable_doc/spec/blocks.schema.json", __DIR__)

  @common %{"id" => :string, "locked" => :boolean, "role" => :string}

  def path, do: @path

  def json, do: Jason.encode!(ordered(schema()), pretty: true) <> "\n"

  def schema do
    blocks = Map.new(Fields.all(), fn {type, fields} -> {type, block(type, fields)} end)

    %{
      "$schema" => "http://json-schema.org/draft-07/schema#",
      "$comment" => "Generated by `mix barkpark.portable_doc.gen_spec`. Do not edit by hand.",
      "title" => "PortableDoc block",
      "description" =>
        "One block of a PortableDoc document. Every type the Barkpark reader renders is " <>
          "under definitions.blocks with its fields and its composition tier (x-tier). " <>
          "x-aliases maps the other spellings the reader accepts to their type. " <>
          "definitions.constraints.declaration is the vocabulary a document type uses to " <>
          "declare its structure.",
      "type" => "object",
      "required" => ["type"],
      "properties" => %{
        "type" => %{"enum" => Enum.sort(Map.keys(blocks) ++ Map.keys(Fields.aliases()))}
      },
      "allOf" =>
        for type <- Enum.sort(Map.keys(blocks)) do
          %{
            "if" => %{
              "properties" => %{"type" => %{"enum" => spellings(type)}},
              "required" => ["type"]
            },
            "then" => %{"$ref" => "#/definitions/blocks/#{type}"}
          }
        end,
      "x-aliases" => Fields.aliases(),
      "definitions" => %{
        "blocks" => blocks,
        "inline" => %{
          "description" =>
            "An inline node (text, link, mark carrier). Its fields are not specified here.",
          "type" => "object",
          "required" => ["type"],
          "properties" => %{"type" => %{"type" => "string"}}
        },
        "constraints" => constraints()
      }
    }
  end

  defp block(type, fields) do
    properties =
      @common
      |> Map.merge(fields)
      |> Map.new(fn {name, shape} -> {name, expand(shape)} end)
      |> Map.put("type", %{"enum" => spellings(type)})

    %{"type" => "object", "x-tier" => Atom.to_string(tier!(type)), "properties" => properties}
  end

  defp tier!(type),
    do: Tiers.tier_of(type) || raise(ArgumentError, "#{type} has no tier in Tiers")

  defp spellings(type) do
    aliases = for {spelling, ^type} <- Fields.aliases(), do: spelling
    Enum.sort([type | aliases])
  end

  defp expand(:any), do: %{}
  defp expand(:scalar), do: %{"type" => ["string", "number"]}
  defp expand(:inline), do: %{"type" => "array", "items" => %{"$ref" => "#/definitions/inline"}}
  defp expand(:block), do: %{"$ref" => "#"}
  defp expand(:blocks), do: %{"type" => "array", "items" => %{"$ref" => "#"}}
  defp expand({:array, item}), do: %{"type" => "array", "items" => expand(item)}

  defp expand({:object, fields}),
    do: %{"type" => "object", "properties" => Map.new(fields, fn {k, v} -> {k, expand(v)} end)}

  defp expand({:any_of, shapes}), do: %{"anyOf" => Enum.map(shapes, &expand/1)}

  defp expand(type) when type in [:string, :integer, :number, :boolean, :object, :array],
    do: %{"type" => Atom.to_string(type)}

  defp constraints do
    {:ok, types} = Code.Typespec.fetch_types(Constraints)

    types
    |> Map.new(fn {:type, {name, spec, []}} -> {Atom.to_string(name), from_typespec(spec)} end)
    |> Map.update!("declaration", fn decl ->
      Map.put(
        decl,
        "description",
        "One structural declaration. Atoms are strings and a {tag, value} pair is a " <>
          "one-key object. A kind is a string that matches a block's role, else its type, " <>
          "or {\"tier\": name}, which matches every block of that tier."
      )
    end)
  end

  defp from_typespec({:atom, _, atom}), do: %{"const" => Atom.to_string(atom)}

  defp from_typespec({:type, _, :union, members}) do
    cond do
      Enum.all?(members, &match?({:atom, _, _}, &1)) ->
        %{"enum" => Enum.map(members, fn {:atom, _, atom} -> Atom.to_string(atom) end)}

      Enum.any?(members, &string_type?/1) ->
        %{"anyOf" => Enum.map(members, &tagged_beside_string/1)}

      true ->
        %{"anyOf" => Enum.map(members, &from_typespec/1)}
    end
  end

  defp from_typespec({:remote_type, _, [{:atom, _, String}, {:atom, _, :t}, []]}),
    do: %{"type" => "string"}

  defp from_typespec({:type, _, :non_neg_integer, []}), do: %{"type" => "integer", "minimum" => 0}
  defp from_typespec({:type, _, :boolean, []}), do: %{"type" => "boolean"}

  defp from_typespec({:type, _, :list, [item]}),
    do: %{"type" => "array", "items" => from_typespec(item)}

  defp from_typespec({:type, _, :tuple, [{:atom, _, tag}, value]}) do
    tag = Atom.to_string(tag)

    %{
      "type" => "object",
      "properties" => %{tag => from_typespec(value)},
      "required" => [tag],
      "additionalProperties" => false
    }
  end

  defp from_typespec({:type, _, :map, fields}) do
    %{
      "type" => "object",
      "properties" =>
        Map.new(fields, fn {:type, _, _, [{:atom, _, key}, value]} ->
          {Atom.to_string(key), from_typespec(value)}
        end),
      "required" =>
        for({:type, _, :map_field_exact, [{:atom, _, key}, _]} <- fields, do: Atom.to_string(key))
    }
  end

  defp from_typespec({:user_type, _, name, []}),
    do: %{"$ref" => "#/definitions/constraints/#{name}"}

  defp from_typespec(spec),
    do: raise(ArgumentError, "no JSON Schema for the typespec #{inspect(spec)}")

  defp string_type?(spec),
    do: match?({:remote_type, _, [{:atom, _, String}, {:atom, _, :t}, []]}, spec)

  defp tagged_beside_string({:user_type, _, name, []} = spec),
    do: from_typespec({:type, 0, :tuple, [{:atom, 0, name}, spec]})

  defp tagged_beside_string(spec), do: from_typespec(spec)

  defp ordered(map) when is_map(map) do
    map
    |> Enum.sort_by(&elem(&1, 0))
    |> Enum.map(fn {k, v} -> {k, ordered(v)} end)
    |> Jason.OrderedObject.new()
  end

  defp ordered(list) when is_list(list), do: Enum.map(list, &ordered/1)
  defp ordered(value), do: value
end
