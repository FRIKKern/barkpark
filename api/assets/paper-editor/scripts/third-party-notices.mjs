#!/usr/bin/env node
// Writes THIRD-PARTY-NOTICES.txt and third-party-notices.json for the packages
// esbuild bundles into bp-paper-editor.bundle.js and bp-paper-editor.css.
//
//   node scripts/third-party-notices.mjs           write both files
//   node scripts/third-party-notices.mjs --check   exit 1 when either file differs
//
// Ported from Barkdown's scripts/editor-notices.mjs. The bundled closure comes
// from esbuild's metafile for the same entry points and options as `npm run
// build`, so a package esbuild tree-shakes away is not listed. Each package's
// LICENSE, COPYING and NOTICE files are copied byte for byte from the locked
// install in node_modules. No network: a bundled package without a notice
// file fails the run instead of being fetched. Output carries no timestamps,
// commit ids or bundle hashes, so it changes only when the closure changes.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const sha256 = (buf) => crypto.createHash("sha256").update(buf).digest("hex");

// The same entry points and options as the `build` script. write:false keeps
// api/priv/static/assets untouched.
const entries = [
  { in: "src/index.js", out: "bp-paper-editor.bundle.js", opts: { format: "iife" } },
  { in: "src/styles.css", out: "bp-paper-editor.css", opts: {} },
];

const packages = new Map(); // "name@version" -> { pkg, dir, assets:Set }
for (const entry of entries) {
  const result = await build({
    absWorkingDir: root,
    entryPoints: [entry.in],
    bundle: true,
    minify: true,
    write: false,
    metafile: true,
    outfile: path.join("../../priv/static/assets", entry.out),
    logLevel: "silent",
    ...entry.opts,
  });
  for (const input of Object.keys(result.metafile.inputs)) {
    if (!input.includes("node_modules/")) continue;
    let dir = path.dirname(path.resolve(root, input));
    let pkg = null;
    while (path.dirname(dir) !== dir) {
      const pj = path.join(dir, "package.json");
      if (fs.existsSync(pj)) {
        pkg = JSON.parse(fs.readFileSync(pj, "utf8"));
        if (pkg.name && pkg.version) break;
      }
      dir = path.dirname(dir);
    }
    if (!pkg?.name) throw new Error(`no owning package.json for ${input}`);
    const key = `${pkg.name}@${pkg.version}`;
    if (!packages.has(key)) packages.set(key, { pkg, dir, assets: new Set() });
    packages.get(key).assets.add(entry.out);
  }
}

const records = [];
const missing = [];
for (const key of [...packages.keys()].sort()) {
  const { pkg, dir, assets } = packages.get(key);
  const names = fs
    .readdirSync(dir)
    .filter((n) => /^(licen[cs]e|copying|notice)/i.test(n) && fs.statSync(path.join(dir, n)).isFile())
    .sort();
  if (!names.length) missing.push(key);
  records.push({
    name: pkg.name,
    version: pkg.version,
    license: typeof pkg.license === "string" ? pkg.license : pkg.license?.type ?? null,
    repository: typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url ?? null,
    bundledInto: [...assets].sort(),
    notices: names.map((n) => {
      const bytes = fs.readFileSync(path.join(dir, n));
      return { file: n, sha256: sha256(bytes), text: bytes.toString("utf8") };
    }),
  });
}
if (missing.length) {
  console.error(`No LICENSE, COPYING or NOTICE file in the installed copy of: ${missing.join(", ")}`);
  console.error("Add the notice text by hand to this script's inputs before shipping.");
  process.exit(1);
}

const self = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
const rule = "=".repeat(78);
let txt = `Third-party notices for ${self.name}\n\n`;
txt += `${self.name} is licensed under ${self.license}; see LICENSE.\n`;
txt += `The files in dist/ bundle the ${records.length} packages listed below.\n`;
txt += "Each package's licence text follows, copied byte for byte from the locked install.\n";
txt += "Generated by scripts/third-party-notices.mjs. Do not edit by hand.\n\n";
for (const r of records) txt += `  ${r.name}@${r.version}  ${r.license ?? "UNKNOWN"}\n`;
for (const r of records) {
  txt += `\n${rule}\n${r.name}@${r.version}\n`;
  txt += `License: ${r.license ?? "UNKNOWN"}\n`;
  if (r.repository) txt += `Repository: ${r.repository}\n`;
  txt += `Bundled into: ${r.bundledInto.join(", ")}\n`;
  for (const n of r.notices) {
    txt += `\n--- ${n.file} ---\n\n${n.text.replace(/\s+$/, "")}\n`;
  }
}

const manifest = {
  package: self.name,
  generator: "scripts/third-party-notices.mjs",
  packages: records.map(({ notices, ...r }) => ({
    ...r,
    notices: notices.map(({ file, sha256 }) => ({ file, sha256 })),
  })),
};
const json = JSON.stringify(manifest, null, 2) + "\n";

const outputs = [
  ["THIRD-PARTY-NOTICES.txt", txt],
  ["third-party-notices.json", json],
];
if (check) {
  let stale = 0;
  for (const [file, body] of outputs) {
    const p = path.join(root, file);
    const cur = fs.existsSync(p) ? fs.readFileSync(p, "utf8") : null;
    if (cur !== body) {
      console.error(`${file} is stale. Run \`npm run notices\` in api/assets/paper-editor and commit the result.`);
      stale = 1;
    }
  }
  if (stale) process.exit(1);
  console.log(`OK notices cover ${records.length} bundled packages`);
} else {
  for (const [file, body] of outputs) fs.writeFileSync(path.join(root, file), body);
  console.log(`Wrote notices for ${records.length} bundled packages`);
}
