// Real mounted canvas: acknowledged external content must land before a host
// advances its revision, including when the human left an idle caret in Paper.
import assert from "node:assert/strict";
import { JSDOM } from "jsdom";
const dom = new JSDOM("<!doctype html><body></body>", { pretendToBeVisual: true, url: "http://localhost/" });
const { window } = dom;
for (const name of ["customElements", "CustomEvent", "document", "DOMParser", "Element", "Event", "EventTarget", "HTMLElement", "KeyboardEvent", "MutationObserver", "Node", "NodeFilter", "Selection", "Text"]) globalThis[name] = window[name];
globalThis.window = window;
Object.defineProperty(globalThis, "navigator", { configurable: true, value: window.navigator });
globalThis.getComputedStyle = window.getComputedStyle.bind(window);
globalThis.requestAnimationFrame = window.requestAnimationFrame.bind(window);
globalThis.cancelAnimationFrame = window.cancelAnimationFrame.bind(window);
globalThis.CSS ||= { escape: String };
window.BP_PAPER_EDITOR_NO_INJECT = true;
await import("../index.js");
const paragraph = (id, text) => ({ id, type: "paragraph", content: [{ type: "text", value: text }] });
const original = [paragraph("one", "Original target."), paragraph("two", "Untouched sibling.")];
const next = [paragraph("one", "Acknowledged agent sentence."), original[1]];
const canvas = document.createElement("bp-paper-canvas");
canvas.acknowledgedSaves = true; canvas.blocks = structuredClone(original);
document.body.append(canvas);
await new Promise(resolve => setTimeout(resolve, 350));
const batches = [];
canvas.addEventListener("bp-canvas-ops", event => batches.push(event.detail));
try {
  canvas._editor.commands.focus("end");
  await new Promise(resolve => setTimeout(resolve, 30));
  const selection = canvas._editor.state.selection;
  assert.equal(canvas._editor.isFocused, true);
  assert.equal(canvas.hasPendingChanges(), false);
  assert.equal(canvas.applyServerBlocksIfIdle(next), true, "idle focus accepts the confirmed content synchronously");
  assert.equal(canvas._editor.state.doc.firstChild.textContent, "Acknowledged agent sentence.");
  assert.equal(canvas._editor.state.selection.$from.parent.textContent, "Untouched sibling.");
  assert.equal(canvas._editor.state.selection.$from.parentOffset, selection.$from.parentOffset, "untouched sibling caret maps through the edit");
  assert.equal(canvas._editor.isFocused, true);
  assert.equal(batches.length, 0, "external content emits no save");
  assert.equal(canvas.hasPendingChanges(), false);
  canvas._editor.view.dispatch(canvas._editor.state.tr.insertText(" Human follows."));
  assert.equal(canvas.applyServerBlocksIfIdle(original), false, "a real debounced draft refuses replacement");
  canvas.flushPendingChanges();
  assert.equal(batches.length, 1);
  assert.equal(canvas.applyServerBlocksIfIdle(original), false, "an in-flight write refuses replacement");
  assert.equal(canvas._editor.state.doc.firstChild.textContent, "Acknowledged agent sentence.");
  assert.match(canvas._editor.state.doc.lastChild.textContent, /Human follows/);
  canvas.acknowledgeOps(batches[0].seq, true);
  const savedReceipt = structuredClone(canvas.blocks);
  assert.equal(canvas.applyServerBlocksIfIdle([paragraph("one", "Newer acknowledged agent."), savedReceipt[1]]), true, "a completed write receipt does not block newer confirmed content");
  canvas.applyServerBlocks(savedReceipt, { mode: "own-stale" });
  assert.equal(canvas._editor.state.doc.firstChild.textContent, "Newer acknowledged agent.", "a late stale own echo cannot revive superseded text");
  assert.match(canvas._editor.state.doc.lastChild.textContent, /Human follows/, "the confirmed update preserves the saved human input");
  assert.equal(canvas.applyServerBlocksIfIdle(next), true);
  const baseline = canvas.blocks;
  canvas._editor.view.input.composing = true;
  assert.equal(canvas.applyServerBlocksIfIdle(original), false, "IME composition is never replaced");
  canvas._editor.view.input.composing = false;
  canvas._mode = "source";
  assert.equal(canvas.applyServerBlocksIfIdle(original), false, "even unchanged source mode waits for explicit exit");
  canvas._mode = "rich";
  const field = document.createElement("input"); canvas.append(field); field.focus();
  assert.equal(canvas.applyServerBlocksIfIdle(original), false, "a node-view input retains ownership");
  field.remove();
  assert.deepEqual(canvas.blocks, baseline, "every refusal retains the acknowledged baseline");
  canvas.applyServerBlocksIfIdle(original);
  canvas._editor.commands.setTextSelection(canvas._editor.state.doc.firstChild.content.size + 1);
  canvas.applyServerBlocksIfIdle(next);
  assert.equal(canvas._editor.state.selection.$from.parent.textContent, "Acknowledged agent sentence.", "takeover stays in the changed target paragraph");
  assert.equal(canvas._editor.state.selection.$from.parentOffset, "Acknowledged agent sentence.".length, "an end caret remains at the new end");
  console.log("PASS idle focused external content, mapped caret, next human input and busy refusals");
} finally { canvas.remove(); window.close(); }
