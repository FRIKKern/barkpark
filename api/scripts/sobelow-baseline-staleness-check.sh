#!/usr/bin/env bash
#
# Ratchet: every entry in api/.sobelow-skips must still point at a real
# construct of its own declared detector type.
#
# WHY THIS EXISTS SEPARATELY FROM sobelow-inline-overlap-check.sh. That check
# is SPAN-BASED and BASELINE-DRIVEN: it asks "is a baseline row also covered by
# an inline annotation?". It therefore PASSES in exactly the situations this
# wave creates — a row that drifted OUT of its annotation span, a row whose
# file was moved or deleted, a file that grew annotations and has zero baseline
# rows. Those are all "no overlap", so it says PASS. This check is orthogonal:
# it never looks at annotations at all. It asks the one question a fingerprint
# baseline can never answer by itself — does `file:line` still hold a call of
# the kind the entry claims to waive?
#
# A baseline entry whose line no longer holds its construct is not a waiver any
# more; it is a dead promise. Sobelow will not match it, so the finding it was
# drawn to cover comes back as NEW (and, in the advisory job, quietly). Worse,
# a dead entry is indistinguishable from a live one by eye, so the reviewed
# baseline slowly stops being reviewed.
#
# NO BEAM, NO DEPS, NO NETWORK. Pure text over the baseline plus the sources it
# names — ~1s — which is why it runs in the BLOCKING job next to the overlap
# ratchet, not in the advisory Sobelow job. Its `--selftest` blocks there
# today; the run against the real baseline is REPORTING-ONLY until the residue
# reaches zero (50 stale on main 2026-07-28, 31 after wave 23 S1), because a
# step that reds on arrival would turn a green, meaningful job permanently red.
# The flip condition and its tracking task are on the workflow step itself.
#
# ANCHOR TOKENS ARE DERIVED, NOT HAND-WRITTEN. The map from detector type to
# the function tokens that type matches is generated by `--derive` directly out
# of the Sobelow detector modules (each detector's
# `Parse.get_fun_vars_and_meta(fun, _, :token, _)` call sites, plus the
# `@..._funs` atom lists a detector iterates when it passes a variable). The
# generated table is embedded below between markers so the blocking job needs
# no deps; `--verify-tokens DIR` regenerates from a real Sobelow checkout and
# reds on any drift, and runs in the advisory Sobelow job where deps exist.
#
# TYPES WITH NO PER-LINE ANCHOR ARE SKIPPED, NEVER PASSED. Config.CSRF,
# Config.Headers and Config.HTTPS are whole-file/whole-router findings — their
# detectors have no per-line token, so there is nothing at `:LINE` to look for.
# They are reported as SKIPPED and excluded from the checked population. A type
# missing from the table entirely is an ERROR (exit 2), not a skip: an unknown
# detector must never be silently waved through.
#
# DIRECTION OF ERROR. The line test is a text match for a call-shaped
# occurrence of the token, so an unrelated line that happens to contain
# `write(` reads as "still resolves". This check is therefore CONSERVATIVE: it
# can miss a stale entry, it cannot invent one. A red here is always real.
#
# EXIT CODES
#   0  every checkable entry still resolves
#   1  one or more entries no longer resolve (listed on stdout)
#   2  fail-closed: usage error, unknown detector type, or ZERO checkable
#      entries. A checker with an empty population has not passed — it has
#      failed to run.

set -euo pipefail

usage() {
  cat <<'USAGE'
usage: sobelow-baseline-staleness-check.sh [--baseline FILE] [--api-dir DIR]
                                           [--derive DIR] [--verify-tokens DIR]
                                           [--selftest]

  --baseline FILE      baseline to check (default: api/.sobelow-skips)
  --api-dir DIR        root the baseline's paths are relative to (default: api/)
  --derive DIR         print the anchor-token table derived from a Sobelow
                       source tree (e.g. api/deps/sobelow) and exit
  --verify-tokens DIR  regenerate from that tree and diff against the table
                       embedded in this script; exit 1 on any drift
  --selftest           run the mutation fixtures that prove this checker can
                       fail, then exit; does not touch the tracked tree
USAGE
}

API_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
BASELINE="$API_DIR/.sobelow-skips"
ROOT_DIR="$API_DIR"
DERIVE_DIR=""
VERIFY_DIR=""
SELFTEST=0

while [[ $# -gt 0 ]]; do
  case $1 in
    --baseline)
      [[ $# -ge 2 ]] || { echo "error: --baseline needs a value" >&2; exit 2; }
      BASELINE=$2
      shift 2
      ;;
    --api-dir)
      [[ $# -ge 2 ]] || { echo "error: --api-dir needs a value" >&2; exit 2; }
      ROOT_DIR=$2
      shift 2
      ;;
    --derive)
      [[ $# -ge 2 ]] || { echo "error: --derive needs a value" >&2; exit 2; }
      DERIVE_DIR=$2
      shift 2
      ;;
    --verify-tokens)
      [[ $# -ge 2 ]] || { echo "error: --verify-tokens needs a value" >&2; exit 2; }
      VERIFY_DIR=$2
      shift 2
      ;;
    --selftest)
      SELFTEST=1
      shift
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    *)
      echo "error: unknown argument: $1" >&2
      usage >&2
      exit 2
      ;;
  esac
done

