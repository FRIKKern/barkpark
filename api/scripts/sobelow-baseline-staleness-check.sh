# Derive the table straight from a Sobelow source tree. Two shapes, both taken
# from the detector modules themselves:
#   * a literal token — `get_fun_vars_and_meta(fun, N, :to_atom, ...)`
#   * a variable token — `get_fun_vars_and_meta(fun, N, file_func, ...)`, where
#     the detector iterates one of its own `@..._funs`/`@..._funcs` atom lists
# A detector with neither has no per-line anchor and is emitted token-less.
derive_tokens() {
  local tree=$1
  if [[ ! -d $tree ]]; then
    echo "error: sobelow source tree not found: $tree" >&2
    return 2
  fi

  local found=0 out
  out=$(
    find "$tree" -type f -name '*.ex' -print0 |
      LC_ALL=C sort -z |
      while IFS= read -r -d '' file; do
        LC_ALL=C awk '
          /@finding_type[[:space:]]+"/ {
            if (type == "") {
              s = $0
              match(s, /"[^:]+:/)
              if (RSTART > 0) type = substr(s, RSTART + 1, RLENGTH - 2)
            }
          }
          # Atom lists the module may iterate: `@code_funs [:a, :b]`,
          # `@file_funcs [...]`, possibly spread over several lines. Collected
          # for every attribute list, used only when a detector passes a
          # variable token (over-collecting only ever widens the match, which
          # is the conservative direction).
          /^[[:space:]]*@[a-z_]+[[:space:]]*\[/ { inlist = 1 }
          inlist {
            rest = $0
            while (match(rest, /:[a-z_][a-zA-Z0-9_]*[!?]?/)) {
              attrs[substr(rest, RSTART + 1, RLENGTH - 1)] = 1
              rest = substr(rest, RSTART + RLENGTH)
            }
            if ($0 ~ /\]/) inlist = 0
          }
          /get_(erlang_)?fun_vars_and_meta\(/ {
            s = $0
            sub(/.*get_(erlang_)?fun_vars_and_meta\(/, "", s)
            n = split(s, arg, ",")
            if (n >= 3) {
              tok = arg[3]
              gsub(/^[[:space:]]+|[[:space:]]+$/, "", tok)
              if (tok ~ /^:[a-z_]/) literal[substr(tok, 2)] = 1
              else needs_attrs = 1
            }
          }
          END {
            if (type == "") exit 0
            out = type
            n = 0
            for (t in literal) toks[++n] = t
            if (needs_attrs) for (t in attrs) toks[++n] = t
            # insertion sort: token order must be stable across awk builds
            for (i = 2; i <= n; i++) {
              v = toks[i]
              for (j = i - 1; j >= 1 && toks[j] > v; j--) toks[j + 1] = toks[j]
              toks[j + 1] = v
            }
            for (i = 1; i <= n; i++)
              if (i == 1 || toks[i] != toks[i - 1]) out = out "\t" toks[i]
            print out
          }
        ' "$file"
      done | LC_ALL=C sort
  )

  [[ -n $out ]] && found=1
  if [[ $found -eq 0 ]]; then
    echo "error: derived ZERO detector types from $tree — refusing to emit an empty table" >&2
    return 2
  fi
  printf '%s\n' "$out"
}

verify_tokens() {
  local tree=$1 fresh
  fresh=$(derive_tokens "$tree") || return $?
  if [[ $fresh == "$ANCHOR_TOKENS" ]]; then
    printf 'PASS: embedded anchor-token table matches the detector modules in %s\n' "$tree"
    return 0
  fi
  echo "FAIL: the embedded anchor-token table has drifted from $tree" >&2
  diff <(printf '%s\n' "$ANCHOR_TOKENS") <(printf '%s\n' "$fresh") >&2 || true
  echo "      Regenerate: api/scripts/sobelow-baseline-staleness-check.sh --derive $tree" >&2
  return 1
}

# --- the check ---------------------------------------------------------------

run_check() {
  if [[ ! -f $BASELINE ]]; then
    echo "error: baseline not found: $BASELINE" >&2
    return 2
  fi
  if [[ ! -d $ROOT_DIR ]]; then
    echo "error: source root not found: $ROOT_DIR" >&2
    return 2
  fi

  local status=0
  awk -v root="${ROOT_DIR%/}" -v baseline="$BASELINE" '
    # Pass 1 (stdin): the derived anchor-token table.
    {
      known[$1] = 1
      line = $0
      sub(/^[^\t]*\t?/, "", line)
      tokens[$1] = line
      next
    }
    function call_regex(toks,   n, i, parts, re) {
      n = split(toks, parts, "\t")
      re = ""
      for (i = 1; i <= n; i++) {
        if (parts[i] == "") continue
        re = (re == "" ? "" : re "|") parts[i]
      }
      if (re == "") return ""
      # A call-shaped occurrence: token preceded by a non-identifier character
      # (start of line, `.`, `|>`, whitespace) and followed by `(`.
      return "(^|[^A-Za-z0-9_])(" re ")[[:space:]]*\\("
    }
    END {
      entries = 0; checked = 0; skipped = 0; stale = 0
      nfiles = 0

      while ((getline row < baseline) > 0) {
        if (row ~ /^[[:space:]]*$/) continue
        entries++

        # `TYPE: human description,relative/path.ex:LINE,FINGERPRINT`
        # The description may contain commas, so anchor on the tail.
        if (match(row, /,[^,]+:[0-9]+,[0-9A-Fa-f]+[[:space:]]*$/) == 0) {
          printf "MALFORMED %s\n", row
          stale++
          continue
        }
        tail = substr(row, RSTART + 1)
        sub(/,[0-9A-Fa-f]+[[:space:]]*$/, "", tail)
        split(tail, loc, ":")
        colon = index(row, ":")
        if (colon == 0) { printf "MALFORMED %s\n", row; stale++; continue }

        e_type[entries] = substr(row, 1, colon - 1)
        e_file[entries] = loc[1]
        e_line[entries] = loc[2] + 0
        # The detector-emitted description often names the exact construct in
        # backticks (`File.write`, `String.to_atom`). When its last segment is
        # one of the type tokens, prefer it — a precise anchor beats the whole
        # family. Otherwise (`XSS`, `System`) fall back to the family.
        desc = substr(row, colon + 1)
        e_hint[entries] = ""
        if (match(desc, /`[A-Za-z_][A-Za-z0-9_.]*[!?]?`/)) {
          hint = substr(desc, RSTART + 1, RLENGTH - 2)
          sub(/^.*\./, "", hint)
          e_hint[entries] = hint
        }

        if (!((e_file[entries] SUBSEP) in seen_file)) {
          seen_file[e_file[entries] SUBSEP] = 1
          files[++nfiles] = e_file[entries]
        }
      }
      close(baseline)

      if (entries == 0) {
        print "error: scanned ZERO baseline entries — refusing to report a pass" > "/dev/stderr"
        exit 2
      }

      # Read every named file once; keep the whole text keyed by line number.
      for (f = 1; f <= nfiles; f++) {
        path = root "/" files[f]
        n = 0
        while ((getline l < path) > 0) { n++; text[files[f], n] = l }
        close(path)
        nlines[files[f]] = n
      }

      for (i = 1; i <= entries; i++) {
        type = e_type[i]
        if (type == "") continue
        if (!(type in known)) {
          printf "error: unknown detector type %s (regenerate the anchor-token table) \n", type > "/dev/stderr"
          exit 2
        }
        re = call_regex(tokens[type])
        if (re == "") {
          if (!(type in skipnote)) {
            skipnote[type] = 1
            printf "SKIP  %s — whole-file/router finding, no per-line anchor to check\n", type
          }
          skipped++
          continue
        }

        checked++
        file = e_file[i]; ln = e_line[i]
        if (nlines[file] == 0) {
          printf "STALE %s:%d %s — file not found under %s\n", file, ln, type, root
          stale++
          continue
        }
        if (ln < 1 || ln > nlines[file]) {
          printf "STALE %s:%d %s — line is past end of file (%d lines)\n",
                 file, ln, type, nlines[file]
          stale++
          continue
        }

        src = text[file, ln]
        hint = e_hint[i]
        if (hint != "" && tokens[type] ~ ("(^|\t)" hint "(\t|$)"))
          want = "(^|[^A-Za-z0-9_])" hint "[[:space:]]*\\("
        else
          want = re

        if (src !~ want) {
          printf "STALE %s:%d %s — line holds no %s call: %s\n",
                 file, ln, type, (hint != "" ? hint : "matching"),
                 substr(src, 1, 80)
          stale++
        }
      }

      if (checked == 0) {
        print "error: ZERO checkable baseline entries — refusing to report a pass" > "/dev/stderr"
        exit 2
      }

      printf "checked %d of %d baseline entries (%d skipped: no per-line anchor)\n",
             checked, entries, skipped
      if (stale > 0) {
        printf "FAIL: %d baseline entries no longer point at a construct of their own type.\n", stale > "/dev/stderr"
        print  "      Each one is a dead waiver: Sobelow will not match it, so the finding" > "/dev/stderr"
        print  "      it was drawn to cover comes back as NEW. Migrate the call site to an" > "/dev/stderr"
        print  "      inline `# sobelow_skip [\"Type\"]` annotation and drop the entry, or" > "/dev/stderr"
        print  "      regenerate on the pinned CI toolchain (sobelow-baseline-reconcile.sh)." > "/dev/stderr"
        exit 1
      }
      print "PASS: every checkable baseline entry still points at a construct of its own type"
    }
  ' <<< "$ANCHOR_TOKENS" || status=$?
  return "$status"
}

# --- selftest: prove the checker can fail, in every direction ----------------

selftest_fixture() {
  local dir=$1
  mkdir -p "$dir/lib/barkpark" "$dir/lib/barkpark_web"
  cat > "$dir/lib/barkpark/fixture.ex" <<'FIXTURE'
defmodule Barkpark.Fixture do
  def resolves(path) do
    File.read!(path)
  end

  def atomize(name) do
    String.to_atom(name)
  end

  def drifted(name) do
    # the construct used to live here
    name
  end
end
FIXTURE
  cat > "$dir/lib/barkpark_web/router.ex" <<'ROUTER'
defmodule BarkparkWeb.Router do
  scope "/" do
    get("/", PageController, :index)
  end
end
ROUTER
}

expect_status() {
  local label=$1 want=$2
  shift 2
  local got=0 out
  out=$("$@" 2>&1) || got=$?
  if [[ $got -ne $want ]]; then
    printf 'SELFTEST FAIL: %s — expected exit %d, got %d\n%s\n' "$label" "$want" "$got" "$out" >&2
    return 1
  fi
  printf '  ok  %-40s exit %d\n' "$label" "$got"
}

run_selftest() {
  local tmp
  tmp=$(mktemp -d "${TMPDIR:-/tmp}/sobelow-staleness-selftest.XXXXXX")
  # shellcheck disable=SC2064
  trap "rm -rf -- '$tmp'" RETURN
  selftest_fixture "$tmp"

  # File.read! is at line 3, String.to_atom at line 7.
  local live="$tmp/live" shifted="$tmp/shifted" moved="$tmp/moved"
  local past="$tmp/past" skiponly="$tmp/skiponly" empty="$tmp/empty"
  local unknown="$tmp/unknown"
  printf '%s\n' \
    'Traversal.FileModule: Directory Traversal in `File.read!`,lib/barkpark/fixture.ex:3,AAAAAA' \
    'DOS.StringToAtom: Unsafe `String.to_atom`,lib/barkpark/fixture.ex:7,BBBBBB' \
    'Config.CSRF: Missing CSRF Protections,lib/barkpark_web/router.ex:2,CCCCCC' \
    > "$live"
  # ONE line off — the entry now lands on `def atomize`, not the call.
  printf '%s\n' \
    'Traversal.FileModule: Directory Traversal in `File.read!`,lib/barkpark/fixture.ex:3,AAAAAA' \
    'DOS.StringToAtom: Unsafe `String.to_atom`,lib/barkpark/fixture.ex:6,BBBBBB' \
    > "$shifted"
  printf '%s\n' \
    'Traversal.FileModule: Directory Traversal in `File.read!`,lib/barkpark/moved_away.ex:3,AAAAAA' \
    > "$moved"
  printf '%s\n' \
    'Traversal.FileModule: Directory Traversal in `File.read!`,lib/barkpark/fixture.ex:9001,AAAAAA' \
    > "$past"
  printf '%s\n' \
    'Config.CSRF: Missing CSRF Protections,lib/barkpark_web/router.ex:2,CCCCCC' \
    > "$skiponly"
  printf '%s\n' \
    'Nope.Invented: Something,lib/barkpark/fixture.ex:3,DDDDDD' \
    > "$unknown"
  : > "$empty"

  echo "selftest: mutation fixtures"
  local failures=0
  local me=${BASH_SOURCE[0]}
  expect_status "every entry resolves" 0 \
    bash "$me" --baseline "$live" --api-dir "$tmp" || failures=1
  expect_status "one entry shifted by ONE line" 1 \
    bash "$me" --baseline "$shifted" --api-dir "$tmp" || failures=1
  expect_status "entry whose file moved away" 1 \
    bash "$me" --baseline "$moved" --api-dir "$tmp" || failures=1
  expect_status "entry past end of file" 1 \
    bash "$me" --baseline "$past" --api-dir "$tmp" || failures=1
  expect_status "only anchorless types fails closed" 2 \
    bash "$me" --baseline "$skiponly" --api-dir "$tmp" || failures=1
  expect_status "zero baseline entries fails closed" 2 \
    bash "$me" --baseline "$empty" --api-dir "$tmp" || failures=1
  expect_status "unknown detector type fails closed" 2 \
    bash "$me" --baseline "$unknown" --api-dir "$tmp" || failures=1

  # The derived table must be derived: an empty tree cannot yield a table.
  expect_status "--derive on a non-tree fails closed" 2 \
    bash "$me" --derive "$tmp/nope" || failures=1

  if [[ $failures -ne 0 ]]; then
    echo "SELFTEST FAILED" >&2
    return 1
  fi
  echo "SELFTEST PASS: the ratchet greens on live entries and reds on a one-line shift, a moved file and a past-EOF line, and fails closed on an unknown type or an empty checkable population"
}

if [[ $SELFTEST -eq 1 ]]; then
  run_selftest
  exit $?
fi

if [[ -n $DERIVE_DIR ]]; then
  derive_tokens "$DERIVE_DIR"
  exit $?
fi

if [[ -n $VERIFY_DIR ]]; then
  verify_tokens "$VERIFY_DIR"
  exit $?
fi

run_check
