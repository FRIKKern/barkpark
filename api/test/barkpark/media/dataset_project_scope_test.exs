defmodule Barkpark.Media.DatasetProjectScopeTest do
  @moduledoc """
  THE PROJECT RUNG OF THE MEDIA READ, and the SQL that proves it is there —
  task-362eccb409365b11.

  ## The defect

  `Search.scope_media_to_dataset/3` filtered `m.dataset_id == ^dataset_id` when
  the dataset resolved and OTHERWISE fell back to `m.dataset == ^dataset`, a
  CALLER-SUPPLIED string. `Tenancy.scope_project_id/1` returned `nil` whenever a
  workspace was present and a project absent, and `Tenancy.get_dataset/2` is a
  PER-PROJECT lookup — so `Search.resolve_dataset_id/2` returned `nil`
  UNCONDITIONALLY for every token-bound non-Default workspace on every flat
  `/v1/media/*` route (a token carries no project binding;
  `Plugs.AssignDefaultScope`'s own moduledoc: "a derived non-Default workspace
  is left project-less").

  Their predicate was permanently `m.dataset == ^string AND m.workspace_id ==
  ^ws`. Two projects in ONE workspace, each holding a dataset slugged
  `production`, returned each other's media: the project rung of the scope
  ladder (`docs/contracts/tenancy.md`) collapsed. Not cross-TENANT — the
  workspace envelope holds either way (`shared_only_sentinel_scope_test.exs`
  pins it) — cross-PROJECT, inside one tenant.

  ## Why a single-project fixture cannot see it

  A query that returns everything and a query that returns the right thing are
  IDENTICAL when only one project exists. `content_cross_project_dataset_scope_test.exs`
  covers Content, not Media. Every fixture below therefore stands up TWO
  projects in ONE workspace with the SAME dataset slug, and asserts on SET
  EQUALITY of returned ids — never on a count, which cannot tell "the right one"
  from "one of them".

  ## Why one of these tests asserts SQL and not rows

  Criterion 0 of the row: an index-only, moduledoc-only or documentation-only
  change leaves the emitted SQL byte-identical. The shape assertion is what
  makes those non-answers fail by definition. It follows the precedent of
  `cursor_sql_shape_test.exs` (same file, same telemetry probe, same reason).
  """
  use Barkpark.DataCase, async: false

  import Barkpark.TenancyFixtures

  alias Barkpark.Media.Delivery.Search
  alias Barkpark.Media.Storage.MediaFile
  alias Barkpark.Repo
  alias Barkpark.Tenancy

  @dataset "production"
  @event [:barkpark, :repo, :query]
  @handler_id :media_dataset_scope_sql_probe

  # ── fixtures ───────────────────────────────────────────────────────────────

  # A workspace shaped the way `create_workspace_with_owner/2` mints one: a
  # `"default"`-slugged project plus a SECOND project, each holding a dataset
  # with the SAME slug. Returns the ids of the two blobs, each stamped with its
  # OWN project's dataset_id — the discrimination fixture.
  defp two_project_workspace! do
    ws = create_workspace!()
    default_project = create_project!(ws, "default")
    sibling_project = create_project!(ws, "sibling")

    {:ok, _} = Tenancy.create_dataset(default_project, %{slug: @dataset, name: @dataset})
    {:ok, _} = Tenancy.create_dataset(sibling_project, %{slug: @dataset, name: @dataset})

    # `create_dataset/2` is `on_conflict: :nothing`, whose returned struct can
    # carry the changeset's autogenerated id rather than the persisted row's.
    # Reload both, exactly as `get_or_create_dataset` does.
    default_ds = Tenancy.get_dataset(default_project, @dataset)
    sibling_ds = Tenancy.get_dataset(sibling_project, @dataset)

    {:ok, mine} =
      create_media_file_in!(ws, default_project, %{dataset_id: default_ds.id}, @dataset)

    {:ok, theirs} =
      create_media_file_in!(ws, sibling_project, %{dataset_id: sibling_ds.id}, @dataset)

    %{
      ws: ws,
      default_project: default_project,
      sibling_project: sibling_project,
      default_ds: default_ds,
      sibling_ds: sibling_ds,
      mine: mine,
      theirs: theirs
    }
  end

  defp search_ids(opts) do
    {files, _total, _facets, _meta} = Search.search(@dataset, opts)
    MapSet.new(files, & &1.id)
  end

  # ── SQL probe (mirrors cursor_sql_shape_test.exs) ──────────────────────────

  defp capture_sql(fun) do
    test = self()

    :telemetry.attach(
      {@handler_id, make_ref()},
      @event,
      fn _event, _measure, meta, _cfg -> send(test, {:sql, meta.query}) end,
      nil
    )

    try do
      fun.()
    after
      for {id, _, _, _} <- :telemetry.list_handlers(@event),
          match?({@handler_id, _}, id),
          do: :telemetry.detach(id)
    end

    drain_sql([])
  end

  defp drain_sql(acc) do
    receive do
      {:sql, sql} -> drain_sql([sql | acc])
    after
      0 -> acc
    end
  end

  defp page_sql(statements) do
    Enum.find(statements, fn sql ->
      String.contains?(sql, ~s(FROM "media_files")) and
        String.contains?(sql, ~s(m0."inserted_at")) and
        String.contains?(sql, "LIMIT")
    end)
  end

  # ── CRITERION 0 — the emitted SQL ──────────────────────────────────────────

  describe "the SQL a non-Default-workspace media search emits" do
    test "filters the blob table on dataset_id, and never on a BARE dataset string" do
      %{ws: ws} = two_project_workspace!()

      sql =
        capture_sql(fn -> Search.search(@dataset, workspace_id: ws.id, limit: 5) end)
        |> page_sql()

      assert sql,
             "no page query reached the Repo — the probe did not observe what it claims to assert"

      assert sql =~ ~r/m0\."dataset_id" = \$\d+/,
             """
             The blob table is NOT filtered on `dataset_id`.

             This is the whole defect: `resolve_dataset_id/2` returned nil for
             every project-less workspace, so the read fell through to a
             caller-supplied `dataset` STRING and the composite index
             `(dataset_id, inserted_at DESC, id DESC)` — whose LEADING column
             this is — could not be used at all.

             An index-only, moduledoc-only or documentation-only change leaves
             this line exactly as it was found.

             Rendered: #{sql}
             """

      # The string leaf may survive ONLY as the NULL-tolerant disjunct — the
      # same shape `join_scope_dataset/3` and `Assets.scope_asset_dataset/3`
      # already use — because `Media.put_scope_attrs/2` legitimately writes
      # unstamped rows. What must NOT survive is a BARE `m0."dataset" = $n`:
      # that is the predicate that swallowed a sibling project's stamped rows.
      # Ecto parenthesises every operand, so the guard is compared against the
      # SAME string with parentheses stripped — the assertion is about which
      # predicates are ANDed together, not about Ecto's bracketing.
      naked = String.replace(sql, ["(", ")"], "")

      for match <- Regex.scan(~r/.{0,60}m0\."dataset" = \$\d+/, naked) do
        [context] = match

        assert context =~ ~r/m0\."dataset_id" IS NULL AND m0\."dataset" = \$\d+/,
               """
               An UNGUARDED `m0."dataset" = $n` predicate is on the blob table.

               A dataset STRING is caller-supplied and is unique only WITHIN a
               project. Unguarded, it matches a sibling project's well-stamped
               rows — the cross-project widening this row exists to close. Every
               occurrence must be pinned to `m0."dataset_id" IS NULL`, which
               makes the two arms disjoint.

               Found: #{context}
               Rendered: #{sql}
               """
      end
    end
  end

  # ── CRITERION 1 — the filter DISCRIMINATES ─────────────────────────────────

  describe "two projects in one workspace, same dataset slug" do
    test "a workspace-scoped, project-LESS search returns EXACTLY its own file" do
      %{ws: ws, mine: mine, theirs: theirs} = two_project_workspace!()

      ids = search_ids(workspace_id: ws.id)

      assert MapSet.member?(ids, mine.id),
             "the caller's OWN file #{mine.id} is not in the result — the read failed closed"

      refute MapSet.member?(ids, theirs.id),
             """
             A SIBLING PROJECT's media file (#{theirs.id}, project
             #{inspect(theirs.project_id)}) came back for a search scoped to
             workspace #{ws.id} with NO project.

             Both projects hold a dataset slugged "#{@dataset}". Before
             task-362eccb409365b11 the predicate was `m.dataset = '#{@dataset}'
             AND m.workspace_id = $ws` — the project rung collapsed and each
             project saw the other's media.
             """

      assert MapSet.equal?(ids, MapSet.new([mine.id])),
             "expected exactly the owner's file, got #{inspect(MapSet.to_list(ids))}"
    end

    test "an EXPLICIT sibling-project scope still reaches the sibling's own file" do
      %{ws: ws, sibling_project: sibling, mine: mine, theirs: theirs} = two_project_workspace!()

      ids = search_ids(workspace_id: ws.id, project_id: sibling.id)

      assert MapSet.member?(ids, theirs.id),
             "an explicit project scope lost the project's OWN file — the fix failed closed"

      refute MapSet.member?(ids, mine.id),
             "the default project's file leaked into an explicit sibling-project read"
    end
  end

  # ── CRITERION 2 — the negative arm ─────────────────────────────────────────

  describe "nobody silently loses rows" do
    test "a legitimately UNSTAMPED row (dataset_id IS NULL) stays reachable by its owner" do
      %{ws: ws, default_project: project, mine: stamped} = two_project_workspace!()

      # Exactly what `Media.put_scope_attrs/2`'s first legit-nil arm writes:
      # `resolve_dataset_id(_attrs, nil) -> {:ok, nil}`. Until this change that
      # arm was UNIVERSAL for a non-Default workspace, so every blob ever
      # uploaded into one looks like this row.
      {:ok, unstamped} = create_media_file_in!(ws, project, %{dataset_id: nil}, @dataset)
      assert is_nil(unstamped.dataset_id)

      ids = search_ids(workspace_id: ws.id)

      assert MapSet.equal?(ids, MapSet.new([stamped.id, unstamped.id])),
             """
             SET EQUALITY failed. Expected the owner's stamped row AND its
             unstamped legacy row; got #{inspect(MapSet.to_list(ids))}.

             A STRICT `m.dataset_id = $n` here would drop every unstamped blob
             to a zero-row 200 — the same availability change a bare fail-closed
             read was rejected for, arriving through the front door.
             """
    end

    test "an unstamped row does NOT leak across the project boundary either" do
      # The unresolved arm is pinned to `dataset_id IS NULL`, so it can no
      # longer swallow a stamped sibling. This checks the OTHER direction: the
      # NULL-tolerant disjunct must not reach a sibling project's UNSTAMPED row
      # by dataset string alone. It is workspace-scoped, and within a workspace
      # an unstamped row carries no project attribution at all — so it is
      # reachable from the workspace read, which is the pre-existing contract.
      %{ws: ws, sibling_project: sibling} = two_project_workspace!()

      {:ok, orphan} = create_media_file_in!(ws, sibling, %{dataset_id: nil}, @dataset)

      ids = search_ids(workspace_id: ws.id)

      assert MapSet.member?(ids, orphan.id),
             """
             An UNSTAMPED row in workspace #{ws.id} became unreachable from that
             workspace's own read. Unstamped rows carry no dataset_id and
             therefore no project attribution; failing them closed is the
             population change this row refused.
             """
    end

    test "the :shared_only sentinel still resolves `workspace_id IS NULL`, not a tenant" do
      # `:shared_only` takes `scope_project_id/1`'s Default arm, so the seeded
      # Default project is what resolves the dataset. Seeding the "production"
      # dataset there DELIBERATELY forces the RESOLVED arm — otherwise this test
      # is order-dependent on whether some other test created that row, and on
      # today's main it flips between passing (unresolved → bare string) and
      # dropping the shared row entirely (resolved → strict `dataset_id = $n`).
      # That flip is itself the evidence for the NULL tolerance: the shared
      # layer's own rows carry NO dataset_id, and a strict arm loses them.
      {_default_ws, seeded_project} = ensure_default_scope!()
      {:ok, _} = Tenancy.create_dataset(seeded_project, %{slug: @dataset, name: @dataset})
      assert %Tenancy.Dataset{} = Tenancy.get_dataset(seeded_project, @dataset)

      %{ws: ws, mine: mine} = two_project_workspace!()

      {:ok, shared} =
        %MediaFile{}
        |> MediaFile.changeset(%{
          filename: "shared.png",
          original_name: "shared.png",
          path: "shared/#{System.unique_integer([:positive])}.png",
          mime_type: "image/png",
          size: 1,
          dataset: @dataset
        })
        |> Repo.insert()

      assert is_nil(shared.workspace_id)

      ids = search_ids(workspace_id: :shared_only)

      assert MapSet.member?(ids, shared.id),
             "the :shared_only sentinel lost the shared layer's own row"

      refute MapSet.member?(ids, mine.id),
             """
             The :shared_only sentinel returned workspace #{ws.id}'s row #{mine.id}.
             The sentinel means `workspace_id IS NULL`, never every tenant.
             """
    end
  end

  # ── the resolution itself ──────────────────────────────────────────────────

  describe "Tenancy.scope_project_id/1" do
    test "resolves a workspace's OWN default project, never the seeded one" do
      {_default_ws, seeded_project} = ensure_default_scope!()

      ws = create_workspace!()
      own_default = create_project!(ws, "default")

      resolved = Tenancy.scope_project_id(workspace_id: ws.id)

      assert resolved == own_default.id

      refute resolved == seeded_project.id,
             """
             The workspace resolved the SEEDED Default Project. That is the
             cross-tenant pairing `AssignDefaultScope` refuses by design: every
             scoped read matches zero rows and every scoped write stamps a
             project_id belonging to another tenant.
             """

      assert Repo.get!(Tenancy.Project, resolved).workspace_id == ws.id
    end

    test "a workspace with no `default`-slugged project still answers nil" do
      ws = create_workspace!()
      _only = create_project!(ws, "other")

      assert is_nil(Tenancy.scope_project_id(workspace_id: ws.id))
    end

    test "an EXPLICIT :project_id still wins, and :shared_only still takes the Default arm" do
      {_default_ws, seeded_project} = ensure_default_scope!()

      ws = create_workspace!()
      _own_default = create_project!(ws, "default")
      explicit = create_project!(ws, "explicit")

      assert Tenancy.scope_project_id(workspace_id: ws.id, project_id: explicit.id) ==
               explicit.id

      assert Tenancy.scope_project_id(workspace_id: :shared_only) == seeded_project.id
      assert Tenancy.scope_project_id([]) == seeded_project.id
    end

    test "a malformed workspace_id answers nil rather than raising Ecto.CastError" do
      assert is_nil(Tenancy.scope_project_id(workspace_id: "not-a-uuid"))
    end
  end
end
